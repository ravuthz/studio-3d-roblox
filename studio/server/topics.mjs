/** a folder name from free text: "In this town, nobody dreams!" -> "in-this-town-nobody-dreams" */
export function slugify(text, words = 8) {
  return String(text || "")
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .split(/[\s-]+/)
    .filter(Boolean)
    .slice(0, words)
    .join("-")
    .slice(0, 48)
    .replace(/-+$/, "");
}

/** ensures a valid lowercase folder slug that is not in `taken` */
export function freeSlug(raw, taken) {
  const cleaned = slugify(raw.replace(/^in-this-town-/, ""), 5) || slugify(raw, 5) || "new-topic";
  for (let i = 1; ; i++) {
    const candidate = i === 1 ? cleaned : `${cleaned.slice(0, 58)}-${i}`;
    if (/^[a-z0-9][a-z0-9-]{0,62}$/.test(candidate) && !taken.has(candidate)) return candidate;
  }
}

/** picks a fresh built-in English topic avoiding existing film names/titles and session repeats */
export function pickTopic({ takenNames = new Set(), takenTitles = new Set() } = {}) {
  const norm = (s) => String(s || "").trim().toLowerCase();
  const fresh = TOPICS.filter((t) => !takenNames.has(t.name) && !takenTitles.has(norm(t.title)));
  if (fresh.length > 0) {
    const pick = fresh[Math.floor(Math.random() * fresh.length)];
    return { name: freeSlug(pick.name, takenNames), title: pick.title, idea: pick.idea };
  }
  // fallback combinatorial generator when all curated topics have been seen
  for (let attempt = 0; attempt < 40; attempt++) {
    const [slug, hook, setup] = RULES[Math.floor(Math.random() * RULES.length)];
    const twist = TWISTS[Math.floor(Math.random() * TWISTS.length)];
    const title = `In this town, ${hook}`;
    if (attempt < 30 && takenTitles.has(norm(title))) continue;
    return {
      name: freeSlug(slug, takenNames),
      title,
      idea: `In Zero's town, ${setup}, while elder brother Zeebra shows off a spotless record to Luna and Zip. Everything changes when ${twist}.`,
    };
  }
  const fallback = TOPICS[Math.floor(Math.random() * TOPICS.length)];
  return { name: freeSlug(fallback.name, takenNames), title: fallback.title, idea: fallback.idea };
}

